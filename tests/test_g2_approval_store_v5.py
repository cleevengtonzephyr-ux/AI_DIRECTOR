class TestConsumptionToPending(_V5TestCase):
    def test_consumption_records_a_pending_enrollment_and_nothing_else(self):
        issued = self._issue()
        credential = _credential()
        pending = self._consume(issued, credential=credential)
        self.assertEqual(pending, PendingEnrollment(issued.invitation_id, APPROVER_ID, PRINCIPAL_ID, ACCOUNT_ID))
        self.assertEqual(self._invitation_state(issued.invitation_id), "CONSUMED")
        credential_id = AttestedCredentialData(credential.credential_data).credential_id
        self.assertEqual(
            self._rows("SELECT invitation_id, account_check, credential_id, created_at_ms, state, closed_at_ms"
                       " FROM pending_enrollments"),
            [(issued.invitation_id, ACCOUNT_CHECK, credential_id, NOW, "PENDING", None)],
        )
        # The stored check says what it is: an unverified mock comparison.
        self.assertEqual(ACCOUNT_CHECK, "MOCK_UNVERIFIED_ACCOUNT_ID_MATCH")
        self.assertEqual(self._registry(), {table: [] for table in REGISTRY_TABLES})

    def test_nothing_is_active_or_visible_to_the_v3_operations(self):
        self._consume()
        for revoke, key, kind in (
            (self.store.revoke_principal, PRINCIPAL_ID, "principal"),
            (self.store.revoke_approver, APPROVER_ID, "approver"),
            (self.store.revoke_account, ACCOUNT_ID, "GitHub account"),
        ):
            with self.subTest(kind=kind):
                with self.assertRaisesRegex(ApprovalRefusedError, "is not registered"):
                    revoke(key)
        self.assertEqual(self._registry(), {table: [] for table in REGISTRY_TABLES})

    def test_a_different_account_id_is_refused_and_leaves_the_invitation_open(self):
        issued = self._issue()
        before = self._snapshot()
        refusal = self._refusal(issued.secret, account_id=OTHER_ACCOUNT_ID)
        self.assertEqual(refusal, (ApprovalRefusedError, "GitHub account does not match the invitation"))
        self.assertNotIn(ACCOUNT_ID, refusal[1])
        self.assertEqual(self._snapshot(), before)
        self.assertEqual(self._consume(issued).account_id, ACCOUNT_ID)

    def test_malformed_account_ids_and_credentials_are_refused_before_any_write(self):
        issued = self._issue()
        before = self._snapshot()
        cases = {
            "account": dict(account_id="042"),
            "account type": dict(account_id=4200001),
            "not a credential": dict(credential=b"credential"),
            "unparsable data": dict(credential=_credential(credential_data=b"x" * 40)),
            "short credential ID": dict(credential=_credential(credential_id=b"short")),
            "empty user handle": dict(credential=_credential(user_handle=b"")),
            "long user handle": dict(credential=_credential(user_handle=b"h" * 65)),
            "BS without BE": dict(credential=_credential(backup_state=True)),
            "BE not a bool": dict(credential=_credential(backup_eligible=1)),
            "negative counter": dict(credential=_credential(sign_count=-1)),
            "counter overflow": dict(credential=_credential(sign_count=1 << 32)),
        }
        for name, kwargs in cases.items():
            with self.subTest(name):
                kind, message = self._refusal(issued.secret, **kwargs)
                self.assertEqual(kind, ApprovalRefusedError)
                self.assertRegex(message, "GitHub account ID|enrollment credential")
        self.assertEqual(self._snapshot(), before)

    def test_unknown_expired_revoked_consumed_and_malformed_secrets_are_refused_identically(self):
        consumed = self._issue()
        self._consume(consumed)
        revoked = self._issue(OTHER_APPROVER_ID, OTHER_PRINCIPAL_ID, OTHER_ACCOUNT_ID)
        self.store.revoke_invitation(revoked.invitation_id)
        expired = self._issue("approver-d", "principal-d", "4200004", expires_at_ms=NOW + 1)
        self.clock.now = NOW + 1
        refusals = {
            "unknown": self._refusal("A" * 43),
            "expired": self._refusal(expired.secret, account_id="4200004", credential=_credential("d")),
            "revoked": self._refusal(revoked.secret, account_id=OTHER_ACCOUNT_ID, credential=_credential("c")),
            "consumed": self._refusal(consumed.secret, credential=_credential("again")),
            "malformed": self._refusal("not-a-secret"),
        }
        self.assertEqual(set(refusals.values()), {(ApprovalRefusedError, UNAVAILABLE)})
        self.assertEqual(self._invitation_state(expired.invitation_id), "EXPIRED")
        self.assertEqual(self._rows("SELECT COUNT(*) FROM pending_enrollments"), [(1,)])

    def test_an_already_registered_or_pending_credential_is_refused_and_writes_nothing(self):
        credential = _credential("shared")
        self._consume(credential=credential)
        other = self._issue(OTHER_APPROVER_ID, OTHER_PRINCIPAL_ID, OTHER_ACCOUNT_ID)
        before = self._snapshot()
        self.assertEqual(
            self._refusal(other.secret, account_id=OTHER_ACCOUNT_ID, credential=credential),
            (ApprovalRefusedError, "enrollment credential is already registered"),
        )
        self.assertEqual(self._snapshot(), before)
        self.assertEqual(self._invitation_state(other.invitation_id), "ISSUED")

    def test_a_pending_enrollment_has_no_expiry(self):
        pending = self._consume()
        columns = {name for (_cid, name, *_rest) in self._rows("PRAGMA table_info(pending_enrollments)")}
        self.assertFalse({name for name in columns if "expir" in name})
        self.clock.now = EXPIRES_AT + 10 * 365 * 86_400_000
        self.assertEqual(self.store.expire_invitations(), 0)
        self.assertEqual(self._enrollment_state(pending.invitation_id), "PENDING")
        self.assertEqual(self._registry(), {table: [] for table in REGISTRY_TABLES})

    def test_a_failure_after_the_consumed_transition_rolls_everything_back(self):
        issued = self._issue()
        before = self._snapshot()
        executed = []
        original_connect = v5_module._v3._connect

        def failing_connect(path, busy_timeout):
            connection = original_connect(path, busy_timeout)
            connection.set_trace_callback(executed.append)

            def deny_enrollment_insert(action, table, _column, _database, trigger):
                if action == sqlite3.SQLITE_INSERT and table == "pending_enrollments" and trigger is None:
                    return sqlite3.SQLITE_DENY
                return sqlite3.SQLITE_OK

            connection.set_authorizer(deny_enrollment_insert)
            return connection

        with mock.patch.object(v5_module._v3, "_connect", failing_connect):
            with self.assertRaisesRegex(ApprovalStoreUnavailableError, "rolled back"):
                self._consume(issued)
        self.assertTrue(any("SET state = 'CONSUMED'" in sql for sql in executed), executed)
        self.assertEqual(self._snapshot(), before)
        self.assertEqual(self._invitation_state(issued.invitation_id), "ISSUED")
        self.assertEqual(self._rows("PRAGMA integrity_check"), [("ok",)])
        self.assertEqual(self._consume(issued).invitation_id, issued.invitation_id)

    def test_concurrent_consumptions_of_one_invitation_record_one_pending_enrollment(self):
        issued = self._issue()
        threads = 6
        barrier = threading.Barrier(threads)
        outcomes, guard = [], threading.Lock()

        def contender(index):
            store = ApprovalStoreV5(self.db_path, self.clock, busy_timeout_seconds=10.0)
            credential = _credential(f"contender-{index}")
            barrier.wait(timeout=60)
            try:
                store.consume_invitation(issued.secret, account_id=ACCOUNT_ID, credential=credential)
                outcome = "PENDING"
            except ApprovalStoreError as error:
                outcome = f"{type(error).__name__}: {error}"
            with guard:
                outcomes.append(outcome)

        workers = [threading.Thread(target=contender, args=(index,)) for index in range(threads)]
        for worker in workers:
            worker.start()
        for worker in workers:
            worker.join(timeout=120)
        self.assertEqual(
            sorted(outcomes), sorted(["PENDING"] + [f"ApprovalRefusedError: {UNAVAILABLE}"] * (threads - 1))
        )
        self.assertEqual(self._rows("SELECT state FROM pending_enrollments"), [("PENDING",)])
        self.assertEqual(self._registry(), {table: [] for table in REGISTRY_TABLES})


