class _V4TestCase(unittest.TestCase):
    def setUp(self):
        self.sandbox = Path(tempfile.mkdtemp(prefix="g2_store_v4_"))
        self.addCleanup(shutil.rmtree, self.sandbox, ignore_errors=True)
        self.db_path = self.sandbox / "approvals-v4.sqlite3"
        self.clock = _Clock()
        self.store = ApprovalStoreV4.initialize(self.db_path, self.clock, busy_timeout_seconds=FAST_BUSY_TIMEOUT)

    def _rows(self, sql, params=(), db_path=None):
        connection = sqlite3.connect(self.db_path if db_path is None else db_path)
        try:
            return connection.execute(sql, params).fetchall()
        finally:
            connection.close()

    def _snapshot(self):
        return {table: self._rows(f"SELECT * FROM {table} ORDER BY 1") for table in TABLES}

    def _write(self, *statements):
        """Direct SQL in one all-or-nothing transaction, as a process with file access could do."""

        connection = sqlite3.connect(self.db_path, autocommit=False)
        try:
            with connection:
                for sql, params in statements:
                    connection.execute(sql, params)
        finally:
            connection.close()

    def _invitation(self, invitation_id):
        rows = self._rows(
            "SELECT state, closed_at_ms FROM enrollment_invitations WHERE invitation_id = ?", (invitation_id,)
        )
        return rows[0] if rows else None

    def _registry(self):
        return (
            self._rows("SELECT principal_id, state FROM principals ORDER BY 1"),
            self._rows("SELECT approver_id, principal_id, state FROM approvers ORDER BY 1"),
        )

    def _issue(self, approver_id=APPROVER_ID, principal_id=PRINCIPAL_ID, expires_at_ms=EXPIRES_AT):
        return self.store.create_invitation(approver_id, principal_id, expires_at_ms=expires_at_ms)

    def _refusal(self, secret):
        with self.assertRaises(ApprovalRefusedError) as context:
            self.store.consume_invitation(secret)
        return type(context.exception), str(context.exception)


