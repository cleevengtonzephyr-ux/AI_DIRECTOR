def _worker(mode, db_path, now, secret_path, sandbox):
    sandbox = Path(sandbox)
    store = ApprovalStoreV4(db_path, lambda: int(now), busy_timeout_seconds=10.0)
    secret = Path(secret_path).read_text(encoding="ascii")

    if mode == "contend":
        (sandbox / f"ready-{os.getpid()}").write_text("1", encoding="utf-8")
        _wait_for((sandbox / "go").exists, "the start signal")
        try:
            store.consume_invitation(secret)
            outcome = "ACTIVATED"
        except ApprovalStoreBusyError:
            outcome = "BUSY"
        except ApprovalRefusedError as error:
            outcome = f"REFUSED: {error}"
        except BaseException as error:  # noqa: B902 -- reported to the test
            outcome = f"ERROR: {error!r}"
        print(json.dumps({"outcome": outcome}))
        return

    if mode == "stop_before_commit":
        # Pause when SQLite is about to run COMMIT: every write of the
        # consumption has executed inside the open transaction.
        seen = []
        original_connect = v4_module._v3._connect

        def stop_at_commit(sql):
            if sql == "COMMIT":
                (sandbox / "stopped").write_text(json.dumps(seen), encoding="utf-8")
                time.sleep(120)
            seen.append(sql)

        def tracing_connect(path, busy_timeout):
            connection = original_connect(path, busy_timeout)
            connection.set_trace_callback(stop_at_commit)
            return connection

        v4_module._v3._connect = tracing_connect
        store.consume_invitation(secret)
    sys.exit(1)


