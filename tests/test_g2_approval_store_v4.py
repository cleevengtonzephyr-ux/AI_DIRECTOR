class TestConsumption(_V4TestCase):
    def test_consumption_activates_the_bound_principal_and_approver_once(self):
        issued = self._issue()
        self.clock.now = NOW + 5_000

        activated = self.store.consume_invitation(issued.secret)

        self.assertEqual(activated, ActivatedApprover(issued.invitation_id, APPROVER_ID, PRINCIPAL_ID))
        self.assertEqual(
            self._registry(),
            ([(PRINCIPAL_ID, "ACTIVE")], [(APPROVER_ID, PRINCIPAL_ID, "ACTIVE")]),
        )
        self.assertEqual(self._invitation(issued.invitation_id), ("CONSUMED", NOW + 5_000))
        self.assertEqual(self._rows("SELECT last_observed_ms FROM store_meta"), [(NOW + 5_000,)])
        self.assertEqual(self._rows("SELECT * FROM github_accounts"), [])
        self.assertEqual(self._rows("SELECT * FROM credentials"), [])
        self.assertEqual(self._rows("SELECT * FROM journal"), [])

        before = self._snapshot()
        self.assertEqual(self._refusal(issued.secret), (ApprovalRefusedError, UNAVAILABLE))
        self.assertEqual(self._snapshot(), before)

    def test_unknown_expired_revoked_consumed_and_malformed_secrets_are_refused_identically(self):
        consumed = self._issue("approver-consumed", "principal-consumed")
        self.store.consume_invitation(consumed.secret)
        revoked = self._issue("approver-revoked", "principal-revoked")
        self.assertTrue(self.store.revoke_invitation(revoked.invitation_id))
        expired = self._issue("approver-expired", "principal-expired", expires_at_ms=NOW + 1_000)
        unknown = "A" * 43
        self.clock.now = NOW + 1_000

        refusals = {
            "unknown": self._refusal(unknown),
            "expired": self._refusal(expired.secret),
            "revoked": self._refusal(revoked.secret),
            "consumed": self._refusal(consumed.secret),
            "already expired": self._refusal(expired.secret),
            "malformed": self._refusal("not-a-secret"),
            "non-string": self._refusal(None),
        }
        self.assertEqual(set(refusals.values()), {(ApprovalRefusedError, UNAVAILABLE)}, refusals)
        for secret in (unknown, expired.secret, revoked.secret, consumed.secret):
            self.assertNotIn(secret, UNAVAILABLE)
        self.assertEqual(self._invitation(expired.invitation_id), ("EXPIRED", NOW + 1_000))
        self.assertEqual(self._invitation(revoked.invitation_id)[0], "REVOKED")
        self.assertEqual(
            self._registry(),
            ([("principal-consumed", "ACTIVE")], [("approver-consumed", "principal-consumed", "ACTIVE")]),
        )

    def test_refusals_other_than_expiry_write_nothing(self):
        consumed = self._issue("approver-consumed", "principal-consumed")
        self.store.consume_invitation(consumed.secret)
        revoked = self._issue()
        self.store.revoke_invitation(revoked.invitation_id)
        self.clock.now = NOW + 7_000
        before = self._snapshot()
        for secret in ("A" * 43, revoked.secret, consumed.secret, "short"):
            with self.subTest(secret=secret[:4]):
                self._refusal(secret)
                self.assertEqual(self._snapshot(), before)

    def test_a_failed_activation_rolls_everything_back(self):
        cases = {
            # The principal insert fails: nothing has been written yet.
            "principal registered meanwhile": (
                ("INSERT INTO principals (principal_id, state) VALUES (?, 'ACTIVE')", (PRINCIPAL_ID,)),
            ),
            # The principal insert succeeds, then the approver insert fails.
            "approver registered meanwhile": (
                ("INSERT INTO principals (principal_id, state) VALUES (?, 'ACTIVE')", (OTHER_PRINCIPAL_ID,)),
                (
                    "INSERT INTO approvers (approver_id, principal_id, state) VALUES (?, ?, 'ACTIVE')",
                    (APPROVER_ID, OTHER_PRINCIPAL_ID),
                ),
            ),
        }
        for name, seed in cases.items():
            with self.subTest(name):
                self.setUp()
                issued = self._issue()
                self._write(*seed)
                self.clock.now = NOW + 3_000
                before = self._snapshot()

                with self.assertRaisesRegex(ApprovalRefusedError, "invitation cannot be activated") as context:
                    self.store.consume_invitation(issued.secret)

                self.assertNotIn(issued.secret, str(context.exception))
                self.assertEqual(self._snapshot(), before)
                self.assertEqual(self._invitation(issued.invitation_id), ("ISSUED", None))
                self.assertEqual(self._rows("SELECT last_observed_ms FROM store_meta"), [(NOW,)])
                self.assertNotIn((PRINCIPAL_ID,), self._rows("SELECT principal_id FROM approvers"))
                self.assertEqual(self._rows("PRAGMA integrity_check"), [("ok",)])

    def test_a_clock_regression_refuses_without_consuming(self):
        issued = self._issue()
        self.clock.now = NOW - 1
        before = self._snapshot()
        with self.assertRaisesRegex(ApprovalRefusedError, "clock moved backwards"):
            self.store.consume_invitation(issued.secret)
        self.assertEqual(self._snapshot(), before)
        self.clock.now = NOW
        self.store.consume_invitation(issued.secret)

    def test_the_activated_rows_follow_the_v3_registry_revocations(self):
        issued = self._issue()
        self.store.consume_invitation(issued.secret)
        self.assertTrue(self.store.revoke_principal(PRINCIPAL_ID))
        self.assertTrue(self.store.revoke_approver(APPROVER_ID))
        self.assertEqual(
            self._registry(),
            ([(PRINCIPAL_ID, "REVOKED")], [(APPROVER_ID, PRINCIPAL_ID, "REVOKED")]),
        )
        self.assertEqual(self._invitation(issued.invitation_id)[0], "CONSUMED")
        with self.assertRaisesRegex(ApprovalRefusedError, "already registered"):
            self._issue(APPROVER_ID, "principal-new")


