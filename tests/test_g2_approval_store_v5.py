class _Clock:
    def __init__(self, now=NOW):
        self.now = now

    def __call__(self):
        return self.now


def _credential(label="credential-b", *, credential_id=None, **overrides):
    private_key = ec.generate_private_key(ec.SECP256R1())
    credential_id = hashlib.sha256(label.encode()).digest() if credential_id is None else credential_id
    data = AttestedCredentialData.create(
        Aaguid.NONE, credential_id, ES256.from_cryptography_key(private_key.public_key())
    )
    values = dict(
        credential_data=bytes(data), user_handle=b"user-handle-b", backup_eligible=False,
        backup_state=False, sign_count=0,
    )
    values.update(overrides)
    return EnrollmentCredential(**values)


