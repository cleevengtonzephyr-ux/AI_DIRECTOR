class TestSchemaV4(_V4TestCase):
    def test_schema_v4_extends_v3_with_the_invitation_table_only(self):
        self.assertEqual(v3_module.SCHEMA_VERSION, 3)
        self.assertEqual(v4_module.SCHEMA_VERSION, 4)
        self.assertEqual(v4_module.APPLICATION_ID, v3_module.APPLICATION_ID)
        self.assertEqual(v4_module._SCHEMA[: len(v3_module._SCHEMA)], v3_module._SCHEMA)
        self.assertEqual(v4_module._SCHEMA[len(v3_module._SCHEMA):], v4_module._INVITATION_SCHEMA)
        self.assertEqual(self._rows("PRAGMA user_version"), [(4,)])
        self.assertEqual(self._rows("PRAGMA application_id"), [(v3_module.APPLICATION_ID,)])
        self.assertEqual(self._rows("PRAGMA journal_mode"), [("wal",)])
        tables = {name for (name,) in self._rows("SELECT name FROM sqlite_schema WHERE type = 'table'")}
        self.assertEqual(tables, set(TABLES))
        self.assertEqual(self._rows("SELECT last_observed_ms FROM store_meta"), [(0,)])

    def test_initialize_never_reuses_an_existing_file(self):
        v3_path = self.sandbox / "existing-v3.sqlite3"
        ApprovalStore.initialize(v3_path, self.clock)
        empty_path = self.sandbox / "empty.sqlite3"
        empty_path.write_bytes(b"")
        for path in (self.db_path, v3_path, empty_path):
            with self.subTest(path=path.name):
                before = path.read_bytes()
                with self.assertRaisesRegex(ApprovalStoreUnavailableError, "already exists"):
                    ApprovalStoreV4.initialize(path, self.clock)
                self.assertEqual(path.read_bytes(), before)
        self.assertEqual(self._rows("PRAGMA user_version", db_path=v3_path), [(3,)])

    def test_initialize_refuses_stale_side_files(self):
        for suffix in ("-wal", "-shm"):
            with self.subTest(suffix=suffix):
                path = self.sandbox / f"stale{suffix}.sqlite3"
                Path(f"{path}{suffix}").write_bytes(b"")
                with self.assertRaisesRegex(ApprovalStoreUnavailableError, "stale database"):
                    ApprovalStoreV4.initialize(path, self.clock)
                self.assertFalse(path.exists())

    def test_v3_and_v4_refuse_each_other(self):
        v3_path = self.sandbox / "v3.sqlite3"
        ApprovalStore.initialize(v3_path, self.clock)
        with self.assertRaisesRegex(ApprovalStoreUnavailableError, "user_version is not the value of schema version 3"):
            ApprovalStore(self.db_path, self.clock)
        with self.assertRaisesRegex(ApprovalStoreUnavailableError, "user_version is not the value of schema version 4"):
            ApprovalStoreV4(v3_path, self.clock)
        self.assertEqual(self._rows("PRAGMA user_version", db_path=v3_path), [(3,)])
        self.assertEqual(self._rows("PRAGMA user_version"), [(4,)])

    def test_a_v4_file_whose_objects_differ_is_refused(self):
        trigger = "enrollment_never_replaced"
        self._write((f"DROP TRIGGER {trigger}", ()))
        with self.assertRaisesRegex(ApprovalStoreUnavailableError, "objects differ from schema version 4"):
            ApprovalStoreV4(self.db_path, self.clock)

        other = self.sandbox / "extra.sqlite3"
        ApprovalStoreV4.initialize(other, self.clock)
        connection = sqlite3.connect(other)
        try:
            connection.execute("CREATE TABLE invitation_secrets (secret TEXT)")
            connection.commit()
        finally:
            connection.close()
        with self.assertRaisesRegex(ApprovalStoreUnavailableError, "objects differ from schema version 4"):
            ApprovalStoreV4(other, self.clock)

    def test_an_absent_file_is_never_created_by_opening(self):
        missing = self.sandbox / "missing.sqlite3"
        with self.assertRaisesRegex(ApprovalStoreUnavailableError, "only an explicit initialize"):
            ApprovalStoreV4(missing, self.clock)
        self.assertFalse(missing.exists())


