class TestConcurrentConsumption(_V4TestCase):
    THREADS = 8
    PROCESSES = 4

    def _secret_file(self, issued):
        path = self.sandbox / "secret.txt"
        path.write_text(issued.secret, encoding="ascii")
        return path

    def _spawn(self, mode, secret_path):
        return subprocess.Popen(
            [sys.executable, "-B", __file__, WORKER_FLAG, mode, str(self.db_path), str(NOW), str(secret_path),
             str(self.sandbox)],
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
        )

    def _assert_single_activation(self, outcomes, winner, loser_prefix):
        self.assertEqual(outcomes.count(winner), 1, outcomes)
        for outcome in outcomes:
            self.assertTrue(outcome == winner or outcome.startswith(loser_prefix), outcome)
        self.assertEqual(
            self._registry(),
            ([(PRINCIPAL_ID, "ACTIVE")], [(APPROVER_ID, PRINCIPAL_ID, "ACTIVE")]),
        )
        self.assertEqual(self._rows("SELECT state FROM enrollment_invitations"), [("CONSUMED",)])

    def test_two_threads_consuming_the_same_secret_activate_once(self):
        issued = self._issue()
        for threads in (2, self.THREADS):
            with self.subTest(threads=threads):
                if threads != 2:
                    self.setUp()
                    issued = self._issue()
                barrier = threading.Barrier(threads)
                outcomes, guard = [], threading.Lock()

                def contender():
                    store = ApprovalStoreV4(self.db_path, self.clock, busy_timeout_seconds=10.0)
                    barrier.wait(timeout=60)
                    try:
                        store.consume_invitation(issued.secret)
                        outcome = "ACTIVATED"
                    except ApprovalStoreError as error:
                        outcome = f"{type(error).__name__}: {error}"
                    with guard:
                        outcomes.append(outcome)

                workers = [threading.Thread(target=contender) for _ in range(threads)]
                for worker in workers:
                    worker.start()
                for worker in workers:
                    worker.join(timeout=120)
                self.assertEqual(len(outcomes), threads)
                # BEGIN IMMEDIATE makes every loser wait, then read CONSUMED.
                self._assert_single_activation(outcomes, "ACTIVATED", f"ApprovalRefusedError: {UNAVAILABLE}")

    def test_processes_consuming_the_same_secret_activate_once(self):
        secret_path = self._secret_file(self._issue())
        workers = [self._spawn("contend", secret_path) for _ in range(self.PROCESSES)]
        try:
            _wait_for(lambda: len(list(self.sandbox.glob("ready-*"))) == self.PROCESSES, "ready workers")
            (self.sandbox / "go").write_text("1", encoding="utf-8")
            outputs = [worker.communicate(timeout=120) for worker in workers]
        finally:
            for worker in workers:
                if worker.poll() is None:
                    worker.kill()
                    worker.communicate(timeout=60)
        outcomes = []
        for stdout, stderr in outputs:
            self.assertTrue(stdout.strip(), stderr[-800:])
            outcomes.append(json.loads(stdout.strip().splitlines()[-1])["outcome"])
        outcomes = ["REFUSED" if outcome == f"REFUSED: {UNAVAILABLE}" else outcome for outcome in outcomes]
        self.assertNotIn("BUSY", outcomes)
        self._assert_single_activation(outcomes, "ACTIVATED", "REFUSED")

    def test_a_stop_before_commit_leaves_the_invitation_issued_and_nothing_activated(self):
        issued = self._issue()
        before = self._snapshot()
        worker = self._spawn("stop_before_commit", self._secret_file(issued))
        stopped = self.sandbox / "stopped"
        try:
            deadline = time.monotonic() + 120
            while not stopped.exists() or not stopped.read_text(encoding="utf-8"):
                if worker.poll() is not None:
                    self.fail(f"worker exited before its stop point: {worker.communicate()[1][-800:]}")
                self.assertLess(time.monotonic(), deadline, "worker never reached its stop point")
                time.sleep(0.01)
            executed = json.loads(stopped.read_text(encoding="utf-8"))
        finally:
            worker.kill()
            worker.communicate(timeout=60)

        # Every activation write ran inside the transaction that was killed.
        writes = [sql for sql in executed if re.match(r"(?i)(insert|update)\b", sql)]
        self.assertTrue(any(sql.startswith("INSERT INTO principals") for sql in writes), writes)
        self.assertTrue(any(sql.startswith("INSERT INTO approvers") for sql in writes), writes)
        self.assertTrue(any("SET state = 'CONSUMED'" in sql for sql in writes), writes)
        self.assertIn("BEGIN IMMEDIATE", executed)

        store = ApprovalStoreV4(self.db_path, self.clock)
        self.assertEqual(self._rows("PRAGMA integrity_check"), [("ok",)])
        self.assertEqual(self._snapshot(), before)
        self.assertEqual(self._invitation(issued.invitation_id), ("ISSUED", None))
        self.assertEqual(
            store.consume_invitation(issued.secret),
            ActivatedApprover(issued.invitation_id, APPROVER_ID, PRINCIPAL_ID),
        )


