class TestInvitationCreation(_V4TestCase):
    def test_only_the_sha256_digest_of_a_256_bit_secret_is_stored(self):
        issued = self._issue()
        self.assertIsInstance(issued, IssuedInvitation)
        self.assertRegex(issued.secret, r"^[A-Za-z0-9_-]{43}$")  # 32 random bytes, base64url
        self.assertRegex(issued.invitation_id, r"^[0-9a-f]{32}$")
        self.assertEqual(issued.expires_at_ms, EXPIRES_AT)

        rows = self._rows("SELECT * FROM enrollment_invitations")
        self.assertEqual(
            rows,
            [(
                issued.invitation_id,
                hashlib.sha256(issued.secret.encode("ascii")).hexdigest(),
                APPROVER_ID,
                PRINCIPAL_ID,
                NOW,
                EXPIRES_AT,
                "ISSUED",
                None,
            )],
        )
        self.assertNotIn(issued.secret, json.dumps(self._snapshot()))
        secret_bytes = issued.secret.encode("ascii")
        for path in self.sandbox.iterdir():
            with self.subTest(file=path.name):
                self.assertNotIn(secret_bytes, path.read_bytes())
        self.assertEqual(self._registry(), ([], []))

    def test_the_secret_never_appears_in_the_representation(self):
        issued = self._issue()
        self.assertNotIn(issued.secret, repr(issued))
        self.assertIn(issued.invitation_id, repr(issued))

    def test_each_invitation_gets_fresh_material(self):
        first = self._issue()
        second = self._issue(OTHER_APPROVER_ID, OTHER_PRINCIPAL_ID)
        self.assertNotEqual(first.secret, second.secret)
        self.assertNotEqual(first.invitation_id, second.invitation_id)

    def test_malformed_bindings_and_expiries_are_refused_without_writing(self):
        before = self._snapshot()
        cases = {
            "approver ID with a space": (" approver", PRINCIPAL_ID, EXPIRES_AT),
            "empty principal ID": (APPROVER_ID, "", EXPIRES_AT),
            "non-string approver ID": (12, PRINCIPAL_ID, EXPIRES_AT),
            "overlong principal ID": (APPROVER_ID, "p" * 129, EXPIRES_AT),
            "boolean expiry": (APPROVER_ID, PRINCIPAL_ID, True),
            "float expiry": (APPROVER_ID, PRINCIPAL_ID, float(EXPIRES_AT)),
            "zero expiry": (APPROVER_ID, PRINCIPAL_ID, 0),
            "expiry beyond SQLite": (APPROVER_ID, PRINCIPAL_ID, 1 << 63),
            "expiry now": (APPROVER_ID, PRINCIPAL_ID, NOW),
            "expiry in the past": (APPROVER_ID, PRINCIPAL_ID, NOW - 1),
        }
        for name, (approver_id, principal_id, expires_at_ms) in cases.items():
            with self.subTest(name):
                with self.assertRaises(ApprovalRefusedError):
                    self.store.create_invitation(approver_id, principal_id, expires_at_ms=expires_at_ms)
        self.assertEqual(self._snapshot(), before)

    def test_a_binding_already_registered_or_already_invited_is_refused(self):
        self._write(
            ("INSERT INTO principals (principal_id, state) VALUES (?, 'ACTIVE')", (OTHER_PRINCIPAL_ID,)),
            (
                "INSERT INTO approvers (approver_id, principal_id, state) VALUES (?, ?, 'ACTIVE')",
                (OTHER_APPROVER_ID, OTHER_PRINCIPAL_ID),
            ),
        )
        for approver_id, principal_id in ((OTHER_APPROVER_ID, PRINCIPAL_ID), (APPROVER_ID, OTHER_PRINCIPAL_ID)):
            with self.subTest(approver_id=approver_id, principal_id=principal_id):
                with self.assertRaisesRegex(ApprovalRefusedError, "already registered"):
                    self.store.create_invitation(approver_id, principal_id, expires_at_ms=EXPIRES_AT)

        self._issue()
        before = self._snapshot()
        for approver_id, principal_id in ((APPROVER_ID, "principal-d"), ("approver-d", PRINCIPAL_ID)):
            with self.subTest(open_invitation=(approver_id, principal_id)):
                with self.assertRaisesRegex(ApprovalRefusedError, "already open for this binding"):
                    self.store.create_invitation(approver_id, principal_id, expires_at_ms=EXPIRES_AT)
        self.assertEqual(self._snapshot(), before)


