class TestNoActivation(_V5TestCase):
    def test_no_primitive_confirms_or_activates_an_enrollment(self):
        self.assertFalse(any("confirm" in name or "activat" in name for name in dir(ApprovalStoreV5)))
        states = self._rows("SELECT sql FROM sqlite_schema WHERE name = 'pending_enrollments'")[0][0]
        self.assertIn("state IN ('PENDING', 'REJECTED')", states)
        self.assertNotIn("CONFIRMED", states)
        self.assertEqual(self._rows("SELECT name FROM sqlite_schema WHERE name LIKE '%confirm%'"), [])

    def test_no_registry_row_and_no_admin_attested_account_is_ever_written(self):
        pending = self._consume()
        rejected = self._consume(
            self._issue(OTHER_APPROVER_ID, OTHER_PRINCIPAL_ID, OTHER_ACCOUNT_ID),
            account_id=OTHER_ACCOUNT_ID, credential=_credential("c"),
        )
        self.store.reject_enrollment(rejected.invitation_id)
        self.store.revoke_invitation(self._issue("approver-d", "principal-d", "4200004").invitation_id)
        self.clock.now = EXPIRES_AT + 1
        self.store.expire_invitations()
        self.assertEqual(self._registry(), {table: [] for table in REGISTRY_TABLES})
        self.assertEqual(self._rows("SELECT * FROM github_accounts WHERE evidence = 'ADMIN_ATTESTED'"), [])
        self.assertEqual(self._enrollment_state(pending.invitation_id), "PENDING")

    def test_rejection_is_final_and_repeated_or_invalid_transitions_are_refused(self):
        pending = self._consume()
        self.assertTrue(self.store.reject_enrollment(pending.invitation_id))
        self.assertEqual(
            self._rows("SELECT state, closed_at_ms FROM pending_enrollments"), [("REJECTED", NOW)]
        )
        issued_only = self._issue(OTHER_APPROVER_ID, OTHER_PRINCIPAL_ID, OTHER_ACCOUNT_ID)
        before = self._snapshot()
        for name, invitation_id in (
            ("reject twice", pending.invitation_id),
            ("reject an unconsumed invitation", issued_only.invitation_id),
            ("reject an unknown invitation", "f" * 32),
        ):
            with self.subTest(name):
                self.assertFalse(self.store.reject_enrollment(invitation_id))
        for malformed in ("", "F" * 32, "f" * 31, None, 7):
            with self.subTest(malformed=malformed):
                with self.assertRaisesRegex(ApprovalRefusedError, "invitation ID is missing or malformed"):
                    self.store.reject_enrollment(malformed)
        self.assertEqual(self._snapshot(), before)
        self.assertEqual(self._registry(), {table: [] for table in REGISTRY_TABLES})


