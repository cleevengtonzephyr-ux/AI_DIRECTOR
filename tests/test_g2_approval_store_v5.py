class _V5TestCase(unittest.TestCase):
    def setUp(self):
        self.sandbox = Path(tempfile.mkdtemp(prefix="g2_store_v5_"))
        self.addCleanup(shutil.rmtree, self.sandbox, ignore_errors=True)
        self.db_path = self.sandbox / "approvals-v5.sqlite3"
        self.clock = _Clock()
        self.store = ApprovalStoreV5.initialize(self.db_path, self.clock, busy_timeout_seconds=FAST_BUSY_TIMEOUT)

    def _rows(self, sql, params=(), db_path=None):
        connection = sqlite3.connect(self.db_path if db_path is None else db_path)
        try:
            return connection.execute(sql, params).fetchall()
        finally:
            connection.close()

    def _snapshot(self):
        return {table: self._rows(f"SELECT * FROM {table} ORDER BY 1") for table in TABLES}

    def _registry(self):
        return {table: self._rows(f"SELECT * FROM {table}") for table in REGISTRY_TABLES}

    def _write(self, *statements):
        """Direct SQL in one all-or-nothing transaction, as a process with file access could do."""

        connection = sqlite3.connect(self.db_path, autocommit=False)
        try:
            with connection:
                for sql, params in statements:
                    connection.execute(sql, params)
        finally:
            connection.close()

    def _invitation_state(self, invitation_id):
        return self._rows("SELECT state FROM enrollment_invitations WHERE invitation_id = ?", (invitation_id,))[0][0]

    def _enrollment_state(self, invitation_id):
        rows = self._rows("SELECT state FROM pending_enrollments WHERE invitation_id = ?", (invitation_id,))
        return rows[0][0] if rows else None

    def _issue(self, approver_id=APPROVER_ID, principal_id=PRINCIPAL_ID, account_id=ACCOUNT_ID,
               expires_at_ms=EXPIRES_AT):
        return self.store.create_invitation(approver_id, principal_id, account_id, expires_at_ms=expires_at_ms)

    def _consume(self, issued=None, account_id=ACCOUNT_ID, credential=None):
        issued = self._issue() if issued is None else issued
        return self.store.consume_invitation(
            issued.secret, account_id=account_id, credential=_credential() if credential is None else credential
        )

    def _refusal(self, secret, **kwargs):
        kwargs.setdefault("account_id", ACCOUNT_ID)
        kwargs.setdefault("credential", _credential())
        with self.assertRaises(ApprovalRefusedError) as context:
            self.store.consume_invitation(secret, **kwargs)
        return type(context.exception), str(context.exception)


