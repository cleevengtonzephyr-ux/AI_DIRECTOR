class TestScopeBoundaries(unittest.TestCase):
    SOURCE = Path(v4_module.__file__).read_text(encoding="utf-8")

    def test_the_v4_store_adds_only_the_invitation_primitives(self):
        v3_public = {name for name in dir(ApprovalStore) if not name.startswith("_")}
        v4_public = {name for name in dir(ApprovalStoreV4) if not name.startswith("_")}
        self.assertEqual(
            v4_public - v3_public,
            {"create_invitation", "consume_invitation", "revoke_invitation", "expire_invitations"},
        )

    def test_the_module_imports_no_network_endpoint_or_provider_code(self):
        tree = ast.parse(self.SOURCE)
        imported = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                imported.update(alias.name for alias in node.names)
            elif isinstance(node, ast.ImportFrom):
                imported.add(node.module)
        self.assertEqual(
            imported,
            {
                "__future__", "functools", "hashlib", "os", "re", "secrets", "sqlite3", "contextlib",
                "dataclasses", "pathlib", "typing", "approval_service", "approval_service.approval_store",
            },
        )
        identifiers = {node.id for node in ast.walk(tree) if isinstance(node, ast.Name)}
        identifiers |= {node.attr for node in ast.walk(tree) if isinstance(node, ast.Attribute)}
        for identifier in identifiers:
            with self.subTest(identifier=identifier):
                self.assertIsNone(re.search(r"(?i)http|socket|urllib|higgsfield|provider", identifier))

    def test_the_only_registry_writes_are_the_two_activation_inserts(self):
        registry = r"(?i)\b(insert|replace)\s+(or\s+\w+\s+)?into\s+(principals|approvers|github_accounts|credentials)\b"
        self.assertEqual(
            [match.group(3) for match in re.finditer(registry, self.SOURCE)],
            ["principals", "approvers"],
        )
        self.assertIsNone(re.search(r"(?i)\bupdate\s+(or\s+\w+\s+)?(principals|approvers|github_accounts)\b",
                                    self.SOURCE))
        self.assertIsNone(re.search(r"(?i)\bdelete\s+from\b", self.SOURCE))

    def test_the_module_documents_that_it_is_no_administration_boundary(self):
        doc = " ".join((v4_module.__doc__ or "").split())
        self.assertIn("authenticates no administrator", doc)
        self.assertIn("proves no person's identity", doc)
        self.assertIn("must not be exposed as an administration interface or connected to a Provider", doc)
        for name in ("create_invitation", "revoke_invitation"):
            method_doc = " ".join((getattr(ApprovalStoreV4, name).__doc__ or "").split())
            self.assertRegex(method_doc, r"does not authenticate its caller|unauthenticated storage primitive")


