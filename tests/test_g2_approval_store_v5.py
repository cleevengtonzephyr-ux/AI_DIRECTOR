def _docstring_nodes(tree):
    nodes = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef)) and node.body:
            first = node.body[0]
            if isinstance(first, ast.Expr) and isinstance(first.value, ast.Constant):
                nodes.add(id(first.value))
    return nodes


class TestScopeBoundaries(unittest.TestCase):
    SOURCE = Path(v5_module.__file__).read_text(encoding="utf-8")

    def test_the_v5_store_adds_only_the_enrollment_primitives(self):
        v3_public = {name for name in dir(ApprovalStore) if not name.startswith("_")}
        v5_public = {name for name in dir(ApprovalStoreV5) if not name.startswith("_")}
        self.assertEqual(
            v5_public - v3_public,
            {"create_invitation", "consume_invitation", "reject_enrollment", "revoke_invitation", "expire_invitations"},
        )
        self.assertEqual(ApprovalStoreV5.__bases__, (ApprovalStore,))

    def test_the_module_imports_no_network_oauth_endpoint_or_provider_code(self):
        tree = ast.parse(self.SOURCE)
        imported = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                imported.update(alias.name for alias in node.names)
            elif isinstance(node, ast.ImportFrom):
                imported.add(node.module)
        self.assertEqual(
            imported,
            {
                "__future__", "functools", "hashlib", "os", "re", "secrets", "sqlite3", "contextlib",
                "dataclasses", "typing", "fido2.webauthn", "approval_service", "approval_service.approval_store",
            },
        )
        identifiers = {node.id for node in ast.walk(tree) if isinstance(node, ast.Name)}
        identifiers |= {node.attr for node in ast.walk(tree) if isinstance(node, ast.Attribute)}
        for identifier in identifiers:
            with self.subTest(identifier=identifier):
                self.assertIsNone(re.search(r"(?i)http|socket|urllib|oauth|oidc|higgsfield|provider", identifier))

    def test_the_module_never_writes_registry_rows_nor_states_an_attestation(self):
        tables = r"(principals|approvers|github_accounts|credentials)\b"
        write = re.compile(r"(?i)\b((insert|replace)\s+(or\s+\w+\s+)?into|update\s+(or\s+\w+\s+)?)\s*" + tables)
        tree = ast.parse(self.SOURCE)
        docstrings = _docstring_nodes(tree)
        for node in ast.walk(tree):
            if isinstance(node, ast.Constant) and isinstance(node.value, str) and id(node) not in docstrings:
                with self.subTest(constant=node.value[:40]):
                    self.assertIsNone(write.search(node.value))
                    # Only docstrings may name these values, to say what v5 is not.
                    self.assertNotIn("ADMIN_ATTESTED", node.value)
                    self.assertNotIn("CONFIRMED", node.value)
                    self.assertNotIn("EXPECTED_GITHUB_USER_ID_MATCHED", node.value)

    def test_the_module_documents_its_limits(self):
        doc = " ".join((v5_module.__doc__ or "").split())
        for phrase in (
            "No principal, approver, GitHub account or credential row is ever written by this module",
            "activation needs a real confirmation by the owner over an authenticated SSH boundary, which does not"
            " exist, so this schema has no confirmation and no CONFIRMED state",
            "It is not a GitHub proof, nor an administrator attestation (``ADMIN_ATTESTED``)",
            "Its primitives are unauthenticated and reserved for isolated tests",
            "must not be exposed through any interface or endpoint, nor connected to a Provider",
            "They run no OAuth exchange and verify no WebAuthn registration",
            "whether it equals an OIDC ``actor_id`` (H1) is not established",
            "It has no expiry",
            "G1 D-5 stays unresolved",
        ):
            with self.subTest(phrase=phrase):
                self.assertIn(phrase, doc)
        for name in ("create_invitation", "consume_invitation", "reject_enrollment", "revoke_invitation"):
            with self.subTest(method=name):
                method_doc = " ".join((getattr(ApprovalStoreV5, name).__doc__ or "").split())
                self.assertRegex(method_doc, r"(?i)does not authenticate its caller|unauthenticated")


