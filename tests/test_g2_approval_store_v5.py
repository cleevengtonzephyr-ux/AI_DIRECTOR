    def test_a_failure_after_every_activation_insert_rolls_everything_back(self):
        pending = self._consume()
        before = self._snapshot()
        executed = []
        original_connect = v5_module._v3._connect

        def failing_connect(path, busy_timeout):
            connection = original_connect(path, busy_timeout)
            connection.set_trace_callback(executed.append)

            def deny_final_update(action, table, _column, _database, trigger):
                if action == sqlite3.SQLITE_UPDATE and table == "pending_enrollments" and trigger is None:
                    return sqlite3.SQLITE_DENY
                return sqlite3.SQLITE_OK

            connection.set_authorizer(deny_final_update)
            return connection

        with mock.patch.object(v5_module._v3, "_connect", failing_connect):
            with self.assertRaisesRegex(ApprovalStoreUnavailableError, "rolled back"):
                self.store.confirm_enrollment(pending.invitation_id)
        for table in ("enrollment_confirmations", *REGISTRY_TABLES):
            with self.subTest(executed=table):
                self.assertTrue(any(sql.startswith(f"INSERT INTO {table}") for sql in executed), executed)
        self.assertEqual(self._snapshot(), before)
        self.assertEqual(self._rows("PRAGMA integrity_check"), [("ok",)])
        self.assertEqual(self.store.confirm_enrollment(pending.invitation_id).account_id, ACCOUNT_ID)

    def test_a_clock_regression_refuses_the_confirmation_without_writing(self):
        pending = self._consume()
