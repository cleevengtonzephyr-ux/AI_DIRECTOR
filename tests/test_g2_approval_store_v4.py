class TestExpiryAndRevocation(_V4TestCase):
    def test_an_invitation_expires_at_its_exact_expiry_instant(self):
        issued = self._issue(expires_at_ms=NOW + 1_000)
        self.clock.now = NOW + 999
        self.assertEqual(self.store.expire_invitations(), 0)
        self.assertEqual(self._invitation(issued.invitation_id), ("ISSUED", None))
        self.clock.now = NOW + 1_000
        self.assertEqual(self._refusal(issued.secret), (ApprovalRefusedError, UNAVAILABLE))
        self.assertEqual(self._invitation(issued.invitation_id), ("EXPIRED", NOW + 1_000))
        self.assertEqual(self._registry(), ([], []))

    def test_expire_invitations_closes_only_the_expired_issued_ones(self):
        early = self._issue("approver-early", "principal-early", expires_at_ms=NOW + 1_000)
        late = self._issue("approver-late", "principal-late", expires_at_ms=NOW + 9_000)
        revoked = self._issue("approver-revoked", "principal-revoked", expires_at_ms=NOW + 1_000)
        self.store.revoke_invitation(revoked.invitation_id)
        self.clock.now = NOW + 2_000

        self.assertEqual(self.store.expire_invitations(), 1)
        self.assertEqual(self.store.expire_invitations(), 0)

        self.assertEqual(self._invitation(early.invitation_id), ("EXPIRED", NOW + 2_000))
        self.assertEqual(self._invitation(late.invitation_id), ("ISSUED", None))
        self.assertEqual(self._invitation(revoked.invitation_id), ("REVOKED", NOW))
        self.store.consume_invitation(late.secret)

    def test_a_new_invitation_may_follow_an_expired_one_for_the_same_binding(self):
        old = self._issue(expires_at_ms=NOW + 1_000)
        self.clock.now = NOW + 1_000
        new = self._issue(expires_at_ms=NOW + 5_000)
        self.assertEqual(self._invitation(old.invitation_id), ("EXPIRED", NOW + 1_000))
        self.assertEqual(self._refusal(old.secret), (ApprovalRefusedError, UNAVAILABLE))
        self.assertEqual(
            self.store.consume_invitation(new.secret),
            ActivatedApprover(new.invitation_id, APPROVER_ID, PRINCIPAL_ID),
        )

    def test_revocation_is_final_and_reports_only_a_real_revocation(self):
        issued = self._issue()
        self.clock.now = NOW + 10
        self.assertTrue(self.store.revoke_invitation(issued.invitation_id))
        self.assertEqual(self._invitation(issued.invitation_id), ("REVOKED", NOW + 10))
        self.assertFalse(self.store.revoke_invitation(issued.invitation_id))
        self.assertFalse(self.store.revoke_invitation("0" * 32))
        self.assertEqual(self._refusal(issued.secret), (ApprovalRefusedError, UNAVAILABLE))
        self.assertEqual(self._registry(), ([], []))

        consumed = self._issue(OTHER_APPROVER_ID, OTHER_PRINCIPAL_ID)
        self.store.consume_invitation(consumed.secret)
        self.assertFalse(self.store.revoke_invitation(consumed.invitation_id))
        self.assertEqual(self._invitation(consumed.invitation_id)[0], "CONSUMED")

    def test_revoking_an_already_expired_invitation_records_its_expiry(self):
        issued = self._issue(expires_at_ms=NOW + 1_000)
        self.clock.now = NOW + 1_500
        self.assertFalse(self.store.revoke_invitation(issued.invitation_id))
        self.assertEqual(self._invitation(issued.invitation_id), ("EXPIRED", NOW + 1_500))

    def test_malformed_invitation_ids_are_refused(self):
        for value in (None, "", "0" * 31, "G" * 32, "0" * 32 + "\n", 12):
            with self.subTest(value=value):
                with self.assertRaisesRegex(ApprovalRefusedError, "invitation ID is missing or malformed"):
                    self.store.revoke_invitation(value)


